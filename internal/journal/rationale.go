// The finished document is a COMPOSITION, not a summary.
//
// Recorded entries are reproduced verbatim and marked [recorded]; facts are
// mined from git and marked [mined]; anything a model contributes is confined
// to a clearly labelled narrative section. That separation is the point — in
// six months the difference between "this reason was written at the time" and
// "a model thought this sounded right" is the difference between a design
// record and a plausible story.

type Fact struct {
	Repo    string
	Branch  string
	Base    string
	Commits []string
	Files   int
	Added   int
	Removed int
}

func git(dir string, args ...string) (string, error) {
	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	out, err := cmd.Output()
	return strings.TrimSpace(string(out)), err
}

// mine collects what git can tell us for certain about each repo in the task.
func mine(cfg *config.Config, slug string, repos []string) []Fact {
	var out []Fact
	for _, name := range repos {
		wt := cfg.RepoDir(slug, name)
		if fi, err := os.Stat(wt); err != nil || !fi.IsDir() {
			continue
		}
		// Ask the worktree rather than deriving the name from the slug: the
		// branch is the user's choice, and this document is a record — naming a
		// branch the work is not on makes it wrong where it matters most.
		branch, _ := git(wt, "rev-parse", "--abbrev-ref", "HEAD")
		f := Fact{Repo: name, Branch: branch}
		// Compare against the merge-base with the branch's origin default, so the
		// diff is the task's own work rather than everything since the fork.
		base := "origin/main"
		if r, ok := cfg.Repo(name); ok {
			if d, err := git(r.Main, "symbolic-ref", "--short", "-q", "refs/remotes/origin/HEAD"); err == nil && d != "" {
				base = d
			}
		}
		mb, err := git(wt, "merge-base", "HEAD", base)
		if err != nil || mb == "" {
			out = append(out, f)
			continue
		}
		f.Base = base
		if s, err := git(wt, "log", "--format=%h %s", mb+"..HEAD"); err == nil && s != "" {
			f.Commits = strings.Split(s, "\n")
		}
		if s, err := git(wt, "diff", "--shortstat", mb, "HEAD"); err == nil && s != "" {
			fmt.Sscanf(s, "%d file", &f.Files)
			for _, part := range strings.Split(s, ",") {
				part = strings.TrimSpace(part)
				if strings.Contains(part, "insertion") {
					fmt.Sscanf(part, "%d", &f.Added)
				}
				if strings.Contains(part, "deletion") {
					fmt.Sscanf(part, "%d", &f.Removed)
				}
			}
		}
		out = append(out, f)
	}
	return out
}

// DocPath is where the document goes: one file for the whole workspace, inside
// a repo so it can be committed and pushed. The first core repo of the task is
// preferred as the host, otherwise its first repo — but the CONTENT
// always spans every repo, because the point is the cross-repo picture.
func DocPath(cfg *config.Config, slug string, repos []string) (string, string) {
	host := ""
	in := map[string]bool{}
	for _, r := range repos {
		in[r] = true
	}
	if cfg.Settings != nil {
		for _, c := range cfg.Settings.CoreRepos {
			if in[c] {
				host = c
				break
			}
		}
	}
	if host == "" && len(repos) > 0 {
		host = repos[0]
	}
	if host == "" {
		return "", ""
	}
	return host, filepath.Join(cfg.RepoDir(slug, host), "docs", "rationale", slug+".md")
}

type Options struct {
	Name    string   // human task name
	Repos   []string // every repo in the workspace
	Narrate string   // optional model-written narrative, already generated
}

// Compose builds the Markdown.
func Compose(cfg *config.Config, slug string, opt Options) (string, error) {
	entries, err := Read(cfg, slug)
	if err != nil {
		return "", err
	}
	facts := mine(cfg, slug, opt.Repos)

	var b strings.Builder
	title := opt.Name
	if title == "" {
		title = slug
	}
	desc := fmt.Sprintf("Design rationale for the %s workspace, spanning %s.",
		slug, strings.Join(opt.Repos, ", "))

	// OKF frontmatter: this document is written to be read later by something
	// that was not here when it was written, so it says what it is rather than
	// leaving that to be inferred from the prose.
	tags := append([]string{"rationale"}, opt.Repos...)
	b.WriteString(Frontmatter{
		Type:        DocType,
		Title:       title,
		Description: desc,
		Timestamp:   time.Now().Format(time.RFC3339),
		Tags:        tags,
	}.Render())

	fmt.Fprintf(&b, "# %s\n\n", title)
	fmt.Fprintf(&b, "%s\n\n", desc)
	fmt.Fprintf(&b, "> Generated by FrIDE on %s. Lines marked **[recorded]** were written by a\n"+
		"> human or agent while the work was happening; **[recorded · user's call]** means the\n"+
		"> choice was settled by the user rather than taken by the agent. Lines marked **[mined]**\n"+
		"> are read from git. Nothing else is inferred, except the clearly marked narrative section.\n\n",
		time.Now().Format("2006-01-02 15:04"))

	section := func(k Kind, heading, empty string) {
		var sel []Entry
		for _, e := range entries {
			if e.Kind == k {
				sel = append(sel, e)
			}
		}
		fmt.Fprintf(&b, "## %s\n\n", heading)
		if len(sel) == 0 {
			fmt.Fprintf(&b, "_%s_\n\n", empty)
			return
		}
		for _, e := range sel {
			stamp := e.Time.Format("2006-01-02 15:04")
			scope := ""
			if e.Repo != "" {
				scope = " · `" + e.Repo + "`"
			}
			src := e.Source
			if src == "" {
				src = "unknown"
			}
			// A user's call is marked in the bullet itself, not only in the _by:_
			// line below it. Someone skimming this document six months from now is
			// reading the bullets; whether a choice was settled by the person who
			// owns the work or taken by an agent on its own is exactly the thing
			// they should not have to look for.
			tag := "recorded"
			if src == SourceUser {
				tag = "recorded · user's call"
			}
			fmt.Fprintf(&b, "- **[%s]** %s%s — %s\n", tag, stamp, scope, e.Text)
			if e.Why != "" {
				fmt.Fprintf(&b, "  - _why:_ %s\n", e.Why)
			}
			fmt.Fprintf(&b, "  - _by:_ %s\n", src)
		}
		b.WriteString("\n")
	}

	// The plan first: it is the thing everything else is judged against.
	section(KindPlan, "Plan", "No plan was recorded for this task.")
	section(KindDecision, "Decisions taken",
		"No decisions were recorded. If choices were made, they were not written down — this is not evidence that none were taken.")
	section(KindAssumption, "Assumptions made",
		"No assumptions were recorded.")
	section(KindIssue, "Issues encountered",
		"No issues were recorded.")

	var notes []Entry
	for _, e := range entries {
		if e.Kind == KindNote {
			notes = append(notes, e)
		}
	}
	if len(notes) > 0 {
		b.WriteString("## Notes\n\n")
		for _, e := range notes {
			fmt.Fprintf(&b, "- **[recorded]** %s — %s\n", e.Time.Format("2006-01-02 15:04"), e.Text)
		}
		b.WriteString("\n")
	}

	b.WriteString("## What changed\n\n")
	if len(facts) == 0 {
		b.WriteString("_No repositories found for this workspace._\n\n")
	}
	for _, f := range facts {
		fmt.Fprintf(&b, "### `%s`\n\n", f.Repo)
		if f.Base != "" {
			fmt.Fprintf(&b, "**[mined]** branch `%s`, diffed against `%s`: %d file(s), +%d / -%d\n\n",
				f.Branch, f.Base, f.Files, f.Added, f.Removed)
		}
		if len(f.Commits) == 0 {
			b.WriteString("_No commits on this branch._\n\n")
			continue
		}
		for _, c := range f.Commits {
			fmt.Fprintf(&b, "- **[mined]** %s\n", c)
		}
		b.WriteString("\n")
	}

	if strings.TrimSpace(opt.Narrate) != "" {
		b.WriteString("## Narrative\n\n")
		b.WriteString("> Written by a model from the material above. It adds no facts and no reasons —\n" +
			"> anything load-bearing should be read in the sections above instead.\n\n")
		b.WriteString(strings.TrimSpace(opt.Narrate))
		b.WriteString("\n")
	}

	return b.String(), nil
}

// Write puts the composed document at its path, creating docs/rationale/.
func Write(cfg *config.Config, slug string, opt Options) (string, error) {
	_, path := DocPath(cfg, slug, opt.Repos)
	if path == "" {
		return "", fmt.Errorf("no repository in this workspace to hold the document")
	}
	doc, err := Compose(cfg, slug, opt)
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return "", err
	}
	if err := os.WriteFile(path, []byte(doc), 0o644); err != nil {
		return "", err
	}
	// A lone document is not a bundle. This directory is one, so it gets the
	// index that makes it readable without opening every file.
	if err := writeDocIndex(filepath.Dir(path)); err != nil {
		return path, err
	}
	return path, nil
}

// writeDocIndex rebuilds docs/rationale/index.md from what is on disk. It is
// not a bundle root — the repository is — so it carries no frontmatter.
func writeDocIndex(dir string) error {
	entries, err := ScanBundle(dir, ".")
	if err != nil {
		return err
	}
	if len(entries) == 0 {
		return nil
	}
	body := RenderIndex("", "", []IndexSection{{Heading: "Design rationale", Entries: entries}})
	return os.WriteFile(filepath.Join(dir, "index.md"), []byte(body), 0o644)
}

// Narrate asks the locally installed agent to join the record up into prose.
//
// It is given ONLY the composed document, never the raw transcripts, and is
// told not to invent reasons — so the worst it can do is rephrase what is
// already there. Optional by design: the document is complete without it.
func Narrate(claudeBin, doc string) (string, error) {
	prompt := "Below is a design-rationale record assembled from entries written during a piece of work.\n" +
		"Write 2-4 short paragraphs that join it into a readable narrative for someone reviewing this " +
		"work later.\n\nRules:\n" +
		"- Do NOT invent reasons, motivations or decisions that are not in the record.\n" +
		"- Do NOT restate the commit list.\n" +
		"- If the record is thin, say so plainly rather than padding it.\n" +
		"- Output prose only, no headings.\n\n---\n\n" + doc

	// The record is untrusted text (agents write it, task archives carry it),
	// and narrating needs no tools: run like the other headless calls — none,
	// clean env, an empty directory, the prompt on stdin.
	dir, err := os.MkdirTemp("", "fride-narrate-")
	if err != nil {
		return "", fmt.Errorf("could not generate the narrative: %w", err)
	}
	defer os.RemoveAll(dir)
	cmd := exec.Command(claudeBin, "-p", "--tools", "", "--permission-mode", "dontAsk", "--no-session-persistence")
	cmd.Dir = dir
	cmd.Stdin = strings.NewReader(prompt)
	cmd.Env = agent.CleanEnv()
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("could not generate the narrative: %w", err)
	}
	return strings.TrimSpace(string(out)), nil
}
